"""flatc struct classes as topic messages: snake_case views and encoding.

Every struct class talos_messages generates carries its schema:
TALOS_SCHEMA_NAME ("control.VelocityTarget"), TALOS_SCHEMA_HASH and
TALOS_SCHEMA_BFBS, the reflection.Schema of its .fbs file. The layout is read
from that schema alone: each field's offset, type, nested struct, fixed
array length and enum, and the struct's bytesize and minalign. A class
without TALOS_SCHEMA_BFBS is not a talos message and raises TypeError.

Fields keep their .fbs names (roller_velocity_rps), so views and
send(**fields) use them, in declaration (memory) order:

- a nested struct flattens to <field>_<subfield> at any depth (pose_x_m);
- a fixed array of scalars or enums ([double:3]) is one field whose value
  is a tuple of exactly that many items (samples_m=(0.0, 1.0, 2.0));
- a fixed array of structs flattens per index to <field>_<i>_<subfield>
  (inners_0_mode, inners_1_offset_m).

Enum-typed fields (and enum arrays) read as plain ints; repr names them.
An omitted field encodes as zero. An unknown field, an array of the wrong
length, or a value its type cannot hold raises TypeError naming the field
and value.

Encoding and decoding run through one little-endian struct.Struct per type,
with explicit zero pad bytes, so the bytes are exactly flatc C++'s.
"""


import enum
import functools
import re
import struct

from reflection.BaseType import BaseType
from reflection.Schema import Schema

# reflection BaseType -> struct format character (scalars a struct can hold).
_CODES = {
    BaseType.Bool: "?", BaseType.Byte: "b", BaseType.UByte: "B",
    BaseType.Short: "h", BaseType.UShort: "H", BaseType.Int: "i",
    BaseType.UInt: "I", BaseType.Long: "q", BaseType.ULong: "Q",
    BaseType.Float: "f", BaseType.Double: "d",
}


def enum_names(cls):
    """{value: name} for an enum.Enum, or for a flatc enum class (int
    attributes); the first name wins for an aliased value."""
    if isinstance(cls, type) and issubclass(cls, enum.Enum):
        return {member: member.name for member in cls}
    names = {}
    for name, value in vars(cls).items():
        if (not name.startswith("_") and isinstance(value, int)
                and not isinstance(value, bool)):
            names.setdefault(value, name)
    return names


def _snake(name):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()


def _text(raw):
    return raw.decode("utf-8")


def _schema_struct(cls):
    """(reflection.Schema, reflection.Object) of cls's struct."""
    label = getattr(cls, "__name__", repr(cls))
    bfbs = getattr(cls, "TALOS_SCHEMA_BFBS", None)
    name = getattr(cls, "TALOS_SCHEMA_NAME", None)
    if bfbs is None or name is None:
        raise TypeError(f"{label} has no TALOS_SCHEMA_BFBS/TALOS_SCHEMA_NAME: "
                        "talos messages are struct classes generated by "
                        "talos_messages")
    data = bytes(bfbs)
    if not Schema.SchemaBufferHasIdentifier(data, 0):
        raise TypeError(f"{label}: TALOS_SCHEMA_BFBS is not a reflection "
                        "schema")
    schema = Schema.GetRootAs(data, 0)
    wanted = name.encode("utf-8")
    for i in range(schema.ObjectsLength()):
        obj = schema.Objects(i)
        if obj.Name() == wanted:
            if not obj.IsStruct():
                raise TypeError(f"{label}: {name} is a table, not a struct")
            return schema, obj
    raise TypeError(f"{label}: TALOS_SCHEMA_BFBS has no struct {name}")


def _enum_names(schema, index):
    names = {}
    if index >= 0:
        values = schema.Enums(index)
        for i in range(values.ValuesLength()):
            value = values.Values(i)
            names.setdefault(value.Value(), _text(value.Name()))
    return names


def _walk(schema, obj, base, prefix, out):
    """Appends (field, offset, code, count or None, enum index) for each
    scalar or scalar array of struct `obj` at byte `base`, in memory order."""
    fields = [obj.Fields(i) for i in range(obj.FieldsLength())]
    for field in sorted(fields, key=lambda f: f.Offset()):
        name = prefix + _snake(_text(field.Name()))
        kind = field.Type()
        offset = base + field.Offset()
        base_type = kind.BaseType()
        if base_type == BaseType.Obj:
            _walk(schema, schema.Objects(kind.Index()), offset, name + "_",
                  out)
        elif base_type == BaseType.Array and kind.Element() == BaseType.Obj:
            sub = schema.Objects(kind.Index())
            for i in range(kind.FixedLength()):
                _walk(schema, sub, offset + i * sub.Bytesize(),
                      f"{name}_{i}_", out)
        elif base_type == BaseType.Array:
            out.append((name, offset, _CODES[kind.Element()],
                        kind.FixedLength(), kind.Index()))
        else:
            out.append((name, offset, _CODES[base_type], None, kind.Index()))


class MessageType:
    """One flatc struct class: its schema, size, fields and codec."""

    def __init__(self, cls):
        schema, obj = _schema_struct(cls)
        self.cls = cls
        self.schema_name = cls.TALOS_SCHEMA_NAME
        self.schema_hash = cls.TALOS_SCHEMA_HASH
        self.size = obj.Bytesize()
        # A target lane's envelope pads to it (talOS/devices/target.h).
        self.alignment = obj.Minalign()
        layout = []
        _walk(schema, obj, 0, "", layout)
        self.fields = tuple(field for field, *_ in layout)
        self._field_set = frozenset(self.fields)
        self.index = {field: i for i, field in enumerate(self.fields)}
        self.enum_names = {  # field -> {value: name}, enum-typed fields only
            field: _enum_names(schema, index)
            for field, _, _, _, index in layout if index >= 0}
        fmt, position = ["<"], 0
        self._arrays = {}  # array field -> length
        self._slot_names, self._slot_codes = [], []  # one per packed value
        for field, offset, code, count, _ in layout:
            if offset > position:
                fmt.append(f"{offset - position}x")
            fmt.append(code if count is None else f"{count}{code}")
            position = offset + struct.calcsize("<" + code) * (count or 1)
            if count is None:
                self._slot_names.append(field)
                self._slot_codes.append(code)
            else:
                self._arrays[field] = count
                self._slot_names.extend(f"{field}[{i}]" for i in range(count))
                self._slot_codes.extend(code * count)
        if self.size > position:
            fmt.append(f"{self.size - position}x")
        self.packer = struct.Struct("".join(fmt))
        if self.packer.size != self.size:
            raise TypeError(f"{cls.__name__}: layout of {self.packer.size} "
                            f"bytes, schema bytesize {self.size}")
        if self._arrays:
            self._groups = []  # (start, length or None) per field
            start = 0
            for field in self.fields:
                count = self._arrays.get(field)
                self._groups.append((start, count))
                start += count or 1
            self.unpack = self._unpack_arrays
        else:
            self.unpack = self.packer.unpack_from

    def _unpack_arrays(self, data):
        values = self.packer.unpack_from(data)
        return tuple(values[start] if count is None
                     else values[start:start + count]
                     for start, count in self._groups)

    def encode(self, fields):
        if not self._field_set.issuperset(fields):
            unknown = set(fields) - self._field_set
            raise TypeError(f"{self.cls.__name__} has no field "
                            f"{', '.join(sorted(unknown))}; it has "
                            f"{', '.join(self.fields)}")
        get = fields.get
        if self._arrays:
            values = []
            for field in self.fields:
                count = self._arrays.get(field)
                if count is None:
                    values.append(get(field, 0))
                    continue
                value = get(field)
                if value is None:
                    values.extend((0,) * count)
                    continue
                try:
                    length = len(value)
                except TypeError:
                    length = None
                if length != count:
                    raise TypeError(f"{self.cls.__name__}: bad value "
                                    f"{value!r} for field {field}: needs "
                                    f"{count} items")
                values.extend(value)
        else:
            values = [get(field, 0) for field in self.fields]
        try:
            return self.packer.pack(*values)
        except (struct.error, OverflowError):
            raise TypeError(self._bad_value(values)) from None

    def _bad_value(self, values):
        """Names the field and value the packer rejected."""
        for field, code, value in zip(self._slot_names, self._slot_codes,
                                      values):
            try:
                struct.pack("<" + code, value)
            except (struct.error, OverflowError) as error:
                return (f"{self.cls.__name__}: bad value {value!r} for "
                        f"field {field}: {error}")
        return f"{self.cls.__name__}: bad field value"

    def decode(self, data):
        return Message(self, data)


@functools.lru_cache(maxsize=None)
def message_type(cls):
    return MessageType(cls)


class Message:
    """A received message: msg.roller_velocity_rps reads that field. The
    fields are unpacked together on the first read and kept."""

    __slots__ = ("_type", "_bytes", "_values")

    def __init__(self, mtype, data):
        self._type = mtype
        self._bytes = bytes(data)
        self._values = None

    def __getattr__(self, name):
        mtype = self._type
        index = mtype.index.get(name)
        if index is None:
            raise AttributeError(f"{mtype.cls.__name__} has no field "
                                 f"{name!r}; it has "
                                 f"{', '.join(mtype.fields)}")
        values = self._values
        if values is None:
            values = self._values = mtype.unpack(self._bytes)
        return values[index]

    def __eq__(self, other):
        return (isinstance(other, Message) and other._type is self._type
                and other._bytes == self._bytes)

    def __repr__(self):
        def named(names, value):
            return names[value] if value in names else repr(value)

        def shown(field):
            value = getattr(self, field)
            names = self._type.enum_names.get(field, {})
            if isinstance(value, tuple):
                items = ", ".join(named(names, item) for item in value)
                return f"({items}{',' if len(value) == 1 else ''})"
            return named(names, value)

        fields = ", ".join(f"{f}={shown(f)}" for f in self._type.fields)
        return f"{self._type.cls.__name__}({fields})"
