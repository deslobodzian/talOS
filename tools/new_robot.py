def check_robot_name(name):
    """Why `name` cannot name a robot, or None. A robot directory is a Bazel
    package and an import root beside talOS/, so it follows the node-name
    rules."""
    problem = new_subsystem.check_name(name)
    return problem.replace("node name", "robot name", 1) if problem else None


def robot_files(robot, name):
    """{workspace-relative path: content} of the robot without a mechanism."""
    configuration = f"{robot}/main_processor/configuration"
    config = f"{configuration}/robot.toml"
    sim_config = f"{configuration}/{new_subsystem.SIM_CONFIGS[0]}"
    docs = posixpath.relpath("docs", robot)
    values = dict(NAME=name, ROBOT=robot, CONFIG=config, PERIOD=PERIOD_US,
                  TIMEOUT=COMMAND_TIMEOUT_US, DOCS=docs, SIM_CONFIG=sim_config)
    return {
        f"{robot}/README.md": fill(README, **values),
        config: fill(ROBOT_TOML, **values),
        sim_config: fill(new_subsystem.SIM_CONFIG_HEADER, **values),
        # A stand-in: new_subsystem regenerates the manifest of every config
        # of the robot that reads robot.toml, so adding the first mechanism
        # writes it.
        sync_manifest.manifest_path(sim_config): "",
        f"{configuration}/subsystems/teleop.toml": TELEOP_TOML,
        f"{configuration}/subsystems/telemetry.toml": TELEMETRY_TOML,
        f"{configuration}/BUILD": fill(CONFIG_BUILD, **values),
    }


def plan(root, name, mechanism, lang, kind="velocity", parent="."):
    """([(path, None, content)], placeholder CAN id) for a new robot at
    <root>/<parent>/<name> with its first mechanism.

    The robot is assembled in a scratch copy of its directory and
    new_subsystem adds the mechanism there, so nothing in the workspace is
    written until both succeed."""
    if problem := check_robot_name(name):
        raise Refused(problem)
    if problem := (new_subsystem.check_name(mechanism)
                   or new_subsystem.check_kind(mechanism, lang, kind)):
        raise Refused(problem)
    real_root = os.path.realpath(root)
    base = os.path.realpath(os.path.join(root, parent))
    if base != real_root and not base.startswith(real_root + os.sep):
        raise Refused(f"--dir {parent} is outside the workspace; a robot "
                      "must be a Bazel package in it")
    robot_dir = os.path.join(base, name)
    if os.path.exists(robot_dir):
        raise Refused(f"{rel(real_root, robot_dir)} already exists")
    robot = rel(real_root, robot_dir)

    with tempfile.TemporaryDirectory() as scratch:
        files = robot_files(robot, name)
        for path, content in files.items():
            full = os.path.join(scratch, path)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as f:
                f.write(content)
        # new_subsystem resolves the config with the real resolver, adds the
        # [[subsystems]] entry and generates robot_manifest.bzl.
        writes, can_id = new_subsystem.plan(scratch, robot, mechanism, lang,
                                            kind)
        for path, _, content in writes:
            files[rel(scratch, path)] = content
    return ([(os.path.join(real_root, path), None, content)
             for path, content in files.items()], can_id)


def next_steps(robot, mechanism, can_id, kind, lang):
    # A new robot has no config_golden_test.cc (only 2026-robot and bench
    # do).
    steps = new_subsystem.next_steps(robot, mechanism, can_id, kind, lang)
    return steps + f"""
  More mechanisms:
    bazel run //tools:new_subsystem -- <name> --lang cpp|py --robot {robot}"""


def main(argv):
    parser = argparse.ArgumentParser(
        prog="bazel run //tools:new_robot --",
        description="Scaffold a talos robot with its first mechanism: "
        "configuration, manifest, graph test and bundle.")
    parser.add_argument("name", help="robot name and directory, e.g. "
                        "my_robot (talOS/NAMING.md node-name rules)")
    parser.add_argument("--mechanism", required=True,
                        help="its first mechanism, as new_subsystem's name")
    parser.add_argument("--lang", choices=("cpp", "py"), required=True,
                        help="the mechanism's language")
    parser.add_argument("--type", dest="kind",
                        choices=("velocity", "position"), default="velocity",
                        help="the mechanism's archetype (default: "
                        "%(default)s)")
    parser.add_argument("--dir", default=".",
                        help="directory to create the robot in, relative to "
                        "the workspace root (default: the root)")
    parser.add_argument("--dry-run", action="store_true",
                        help="print every file without writing")
    args = parser.parse_args(argv)

    root = os.environ.get("BUILD_WORKSPACE_DIRECTORY")
    if not root:
        print("new_robot: BUILD_WORKSPACE_DIRECTORY is unset; run it with "
              "`bazel run //tools:new_robot -- ...`", file=sys.stderr)
        return 2
    try:
        writes, can_id = plan(root, args.name, args.mechanism, args.lang,
                              args.kind, args.dir)
    except Refused as refused:
        print(f"new_robot: refused: {refused}", file=sys.stderr)
        return 1

    if args.dry_run:
        new_subsystem.show(root, writes)
    else:
        for path, _, content in writes:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            print(f"wrote {shown(root, path)}")
    real_root = os.path.realpath(root)
    robot = rel(real_root, os.path.join(real_root, args.dir, args.name))
    print(next_steps(robot, args.mechanism, can_id, args.kind, args.lang))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
